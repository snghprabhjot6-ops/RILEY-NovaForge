const languageLocales = { en: "en-US", hi: "hi-IN", fr: "fr-FR", bn: "bn-BD", sa: "sa-IN", es: "es-ES" };
const speechVoices = window.speechSynthesis;
const form = document.querySelector("#composer");
const input = document.querySelector("#message-input");
const sendButton = document.querySelector("#send-button");
const messages = document.querySelector("#messages");
const welcome = document.querySelector("#welcome");
const languageSelect = document.querySelector("#language");
const voiceToggle = document.querySelector("#voice-toggle");
const imageInput = document.querySelector("#image-input");
const attachmentPreview = document.querySelector("#attachment-preview");
const toast = document.querySelector("#toast");
const micButton = document.querySelector("#mic-button");
let attachedImage = null;
let imageLoadId = 0;
let toastTimer;
let recognition;
let activeMode = "chat";

function language() {
  return translations[languageSelect.value] || translations.en;
}

function showToast(message) {
  toast.textContent = message;
  toast.classList.add("visible");
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => toast.classList.remove("visible"), 2800);
}

function addMessage(text, role, imageCanvas) {
  const message = document.createElement("article");
  message.className = `message ${role}`;
  const avatar = document.createElement("span");
  avatar.className = "message-avatar";
  avatar.setAttribute("aria-hidden", "true");
  avatar.textContent = role === "user" ? "Y" : "R";
  const content = document.createElement("div");
  content.className = "message-content";
  const label = document.createElement("span");
  label.className = "message-label";
  label.textContent = role === "user" ? "You" : "Riley";
  content.append(label, document.createTextNode(text));
  if (imageCanvas) {
    const preview = document.createElement("canvas");
    preview.width = imageCanvas.width;
    preview.height = imageCanvas.height;
    preview.getContext("2d").drawImage(imageCanvas, 0, 0);
    preview.setAttribute("role", "img");
    preview.setAttribute("aria-label", language().imageAttached);
    content.append(preview);
  }
  message.append(avatar, content);
  messages.append(message);
  message.scrollIntoView({ behavior: "smooth", block: "nearest" });
}

function addAssistantResponse(imageIncluded) {
  const response = imageIncluded ? language().imageResponse : language().response;
  addMessage(response, "assistant");
  if (voiceToggle.getAttribute("aria-pressed") === "true") speak(response);
}

function submitMessage(text = input.value) {
  const cleanText = text.trim();
  if (!cleanText && !attachedImage) {
    showToast(language().empty);
    return;
  }
  welcome.hidden = true;
  addMessage(cleanText || language().imageAttached, "user", attachedImage?.canvas);
  const hadImage = Boolean(attachedImage);
  clearAttachment();
  input.value = "";
  input.style.height = "auto";
  sendButton.disabled = true;
  window.setTimeout(() => addAssistantResponse(hadImage), 250);
}

function clearAttachment() {
  imageLoadId += 1;
  attachedImage = null;
  imageInput.value = "";
  attachmentPreview.replaceChildren();
  attachmentPreview.hidden = true;
}

function updateLanguage() {
  const lang = language();
  document.documentElement.lang = languageLocales[languageSelect.value] || "en";
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (lang[key]) element.textContent = lang[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    element.placeholder = lang[element.dataset.i18nPlaceholder];
  });
  if (activeMode === "chat") input.placeholder = lang.messagePlaceholder;
  else if (activeMode === "code") input.placeholder = lang.codePlaceholder;
  else input.placeholder = lang.visionPlaceholder;
  voiceToggle.setAttribute("aria-label", lang[voiceToggle.getAttribute("aria-pressed") === "true" ? "voiceOn" : "voiceOff"]);
  micButton.setAttribute("aria-label", lang.dictate);
  micButton.title = lang.dictate;
}

function speak(text) {
  if (!speechVoices) {
    showToast(language().voiceUnavailable);
    voiceToggle.setAttribute("aria-pressed", "false");
    updateLanguage();
    return;
  }
  speechVoices.cancel();
  const utterance = new SpeechSynthesisUtterance(text);
  const locale = languageLocales[languageSelect.value] || "en-US";
  const voices = speechVoices.getVoices();
  const suitable = voices.filter((voice) => voice.lang.toLowerCase().startsWith(locale.split("-")[0].toLowerCase()));
  utterance.voice = suitable.find((voice) => /female|woman|zira|samantha|karen|susan|victoria|heera|kalpana|lekha|veena|raveena|google हिन्दी|google français/i.test(voice.name))
    || suitable[0]
    || null;
  utterance.lang = locale;
  speechVoices.speak(utterance);
}

document.querySelector("#new-chat").addEventListener("click", () => {
  messages.replaceChildren();
  welcome.hidden = false;
  clearAttachment();
  input.value = "";
  sendButton.disabled = true;
  input.focus();
});

